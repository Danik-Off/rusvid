/**
 * Вход во ВКонтакте — сессией сайта, без регистрации приложения.
 *
 * Раньше здесь был OAuth Implicit Flow, и он требовал от пользователя
 * завести собственное приложение VK и вручную вписать его `client_id`.
 * Для приложения-агрегатора это неприемлемый барьер: человек хочет
 * посмотреть видео, а не читать документацию для разработчиков.
 *
 * Теперь VK работает так же, как Rutube и Sasflix: открывается обычный
 * сайт VK Видео во встроенном браузере, пользователь входит привычным
 * способом (телефон, почта, QR-код, VK ID), а сессия остаётся в системном
 * хранилище cookie Android, которое `WebView` и сетевой стек React Native
 * делят между собой. Пароль через наш код не проходит.
 *
 * **Вход не обязателен.** Поиск, витрина, разделы и карточки видео
 * работают анонимно (см. vkTokens.ts). Вход добавляет к ним персональную
 * выдачу и разделы вошедшего человека.
 */

import type { WebLoginSpec } from '../../core/provider/auth';

/**
 * Сайт VK Видео. Именно он, а не `vk.com`: cookie-сессию, которую потом
 * меняют на токен (`video.getWebToken` на `api.vkvideo.ru`), проверяет
 * поддомен `vkvideo.ru`, и заводить её нужно на этом же домене. Пока вход
 * шёл через `vk.com/login`, сессия оседала на другом домене, и обмен на
 * токен не мог состояться.
 */
export const VK_WEB_ORIGIN = 'https://vkvideo.ru';

export const vkAuthSpec: WebLoginSpec = {
  kind: 'webLogin',
  benefit: 'Персональная выдача и ваши разделы VK Видео',
  loginUrl: `${VK_WEB_ORIGIN}/`,
  instructions:
    'Нажмите «Войти» в шапке сайта и войдите как обычно — по номеру телефона, ' +
    'почте или QR-коду. Регистрировать приложение и вводить какие-либо ключи ' +
    'не нужно: приложение подхватит сессию сайта само. Вход не обязателен — ' +
    'поиск и витрина VK Видео работают и без него.',
  // Метод, который меняет cookie-сессию на пользовательский токен: получилось —
  // значит, вход состоялся. См. VkProvider.verifySession.
  verifySessionPath: '/method/video.getWebToken',
  /**
   * Все домены обязательны. VK размазывает сессию по своим площадкам и умеет
   * восстанавливать её автологином (`login.vk.ru?act=autologin`), поэтому
   * выход, погасивший cookie только на одном домене, отменялся бы первым же
   * заходом на любой другой.
   */
  sessionOrigins: [
    VK_WEB_ORIGIN,
    'https://api.vkvideo.ru',
    'https://vk.com',
    'https://login.vk.com',
    'https://id.vk.com',
    'https://vk.ru',
    'https://login.vk.ru',
    'https://id.vk.ru',
    'https://oauth.vk.ru',
  ],
  logoutUrl: `${VK_WEB_ORIGIN}/`,
};
