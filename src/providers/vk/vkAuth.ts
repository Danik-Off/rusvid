/**
 * Вход во ВКонтакте — сессией сайта, без регистрации приложения.
 *
 * Раньше здесь был OAuth Implicit Flow, и он требовал от пользователя
 * завести собственное приложение VK и вручную вписать его `client_id`.
 * Для приложения-агрегатора это неприемлемый барьер: человек хочет
 * посмотреть видео, а не читать документацию для разработчиков.
 *
 * Теперь VK работает так же, как Rutube и Sasflix: открывается обычная
 * страница входа ВКонтакте во встроенном браузере, пользователь входит
 * привычным способом (телефон, почта, QR-код, VK ID), а сессия остаётся
 * в системном хранилище cookie Android, которое `WebView` и сетевой стек
 * React Native делят между собой. Пароль через наш код не проходит.
 *
 * Чужой `client_id` (официального клиента VK) сюда сознательно НЕ
 * подставляется: это означало бы выдавать приложение за первую сторону
 * платформы.
 */

import type { WebLoginSpec } from '../../core/provider/auth';

/**
 * Вход начинается с VK Видео, а не с vk.com: анонимный заход туда сразу
 * уводит на страницу входа VK ID, и пользователю не нужно самому искать
 * кнопку «Войти».
 */
export const VK_VIDEO_ORIGIN = 'https://vkvideo.ru';

export const vkAuthSpec: WebLoginSpec = {
  kind: 'webLogin',
  benefit: 'Поиск по видео VK и ваши подписки',
  loginUrl: `${VK_VIDEO_ORIGIN}/`,
  instructions:
    'Войдите во ВКонтакте как обычно — по номеру телефона, почте или QR-коду. ' +
    'Регистрировать приложение и вводить какие-либо ключи не нужно: приложение ' +
    'подхватит сессию сайта само.',
  // Внутренний endpoint веб-клиента: без сессии VK отвечает на него отказом,
  // с сессией — полезной нагрузкой. См. VkWebClient.probeSession.
  verifySessionPath: '/al_video.php',
  logoutUrl: `${VK_VIDEO_ORIGIN}/`,
};
