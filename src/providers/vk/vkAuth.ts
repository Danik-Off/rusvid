/**
 * Вход во ВКонтакте — сессией сайта, без регистрации приложения.
 *
 * Раньше здесь был OAuth Implicit Flow, и он требовал от пользователя
 * завести собственное приложение VK и вручную вписать его `client_id`.
 * Для приложения-агрегатора это неприемлемый барьер: человек хочет
 * посмотреть видео, а не читать документацию для разработчиков.
 *
 * Теперь VK работает так же, как Rutube и Sasflix: открывается обычная
 * страница входа ВКонтакте во встроенном браузере, пользователь входит
 * привычным способом (телефон, почта, QR-код, VK ID), а сессия остаётся
 * в системном хранилище cookie Android, которое `WebView` и сетевой стек
 * React Native делят между собой. Пароль через наш код не проходит.
 *
 * Чужой `client_id` (официального клиента VK) сюда сознательно НЕ
 * подставляется: это означало бы выдавать приложение за первую сторону
 * платформы.
 */

import type { WebLoginSpec } from '../../core/provider/auth';

/**
 * Домен, на котором живут внутренние endpoint'ы веб-клиента (`al_*.php`)
 * и, главное, cookie-сессия пользователя.
 *
 * Именно `vk.com`, а не `vkvideo.ru`. Это не косметика: `vkvideo.ru` —
 * отдельный фронтенд, и `POST /al_video.php` он отдаёт **404**. Пока вход
 * и проверка сессии шли через `vkvideo.ru`, кнопка «Я вошёл» не могла
 * сработать ни при каких условиях — приложение спрашивало про сессию
 * несуществующую страницу. Ссылки на плеер и страницы видео тоже собираются
 * на `vk.com` (см. vkVideoId.ts), так что весь путь данных живёт на одном
 * домене и на одной cookie.
 */
export const VK_WEB_ORIGIN = 'https://vk.com';

export const vkAuthSpec: WebLoginSpec = {
  kind: 'webLogin',
  benefit: 'Поиск по видео VK и ваши подписки',
  // Страница входа, а не главная: анонимный заход на `vkvideo.ru`
  // прокидывал пользователя через autologin обратно на главную с
  // `errorCode=11300` и без всякой формы.
  loginUrl: `${VK_WEB_ORIGIN}/login`,
  instructions:
    'Войдите во ВКонтакте как обычно — по номеру телефона, почте или QR-коду. ' +
    'Регистрировать приложение и вводить какие-либо ключи не нужно: приложение ' +
    'подхватит сессию сайта само.',
  // Внутренний endpoint веб-клиента: в его ответе VK всегда сообщает
  // идентификатор текущего пользователя. См. VkWebClient.probeSession.
  verifySessionPath: '/al_video.php',
  // Все три домена обязательны. VK умеет восстанавливать сессию между своими
  // площадками (`login.vk.ru?act=autologin`), поэтому выход только с vk.com
  // отменялся бы первым же заходом на vkvideo.ru.
  sessionOrigins: [VK_WEB_ORIGIN, 'https://vkvideo.ru', 'https://login.vk.ru'],
  logoutUrl: `${VK_WEB_ORIGIN}/`,
};
