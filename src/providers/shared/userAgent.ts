/**
 * User-Agent, которым приложение представляется сайтам платформ.
 *
 * Один на всех и ровно один: `WebView` экрана входа и обычные запросы
 * провайдеров — это один и тот же браузер устройства, работающий с одной и
 * той же сессией пользователя, и представляться они обязаны одинаково.
 * Платформы привязывают cookie-сессию к клиенту не только по самой cookie:
 * сессия, заведённая в WebView, при запросе с другим User-Agent считается
 * чужой, и вместо данных приходит страница входа.
 *
 * Это вопрос совместимости, а не маскировки: приложение действительно ходит
 * из системного WebView Android, и строка описывает именно его. Никакие
 * ограничения доступа таким образом не обходятся — платформа отдаёт ровно то
 * же, что отдала бы браузеру этого пользователя.
 *
 * Мобильный, а не десктопный: в десктопной вёрстке форма входа у некоторых
 * платформ спрятана глубже, а VK для мобильного клиента отдаёт лёгкий
 * `m.vk.com`, который открывается во встроенном браузере быстрее.
 */
export const MOBILE_USER_AGENT =
  'Mozilla/5.0 (Linux; Android 13; Pixel 7) AppleWebKit/537.36 (KHTML, like Gecko) ' +
  'Chrome/122.0.0.0 Mobile Safari/537.36';
