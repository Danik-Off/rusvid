/**
 * Обёртка над нативным модулем cookie-сессий.
 *
 * В отличие от `screenControl`, отсутствие модуля здесь НЕ проглатывается.
 * Разница принципиальная: без скрытия системных полос приложение просто
 * выглядит хуже, а «выход», который ничего не очистил, — это ложь
 * пользователю о том, где лежат его данные. Лучше честная ошибка.
 */

import NativeWebSession from '../../specs/NativeWebSession';

export const webSession = {
  /** Собрался ли нативный модуль. */
  available: NativeWebSession !== null,

  /** Выйти с сайтов платформы: погасить её cookie на всех её доменах. */
  async clearCookies(origins: readonly string[]): Promise<void> {
    if (!NativeWebSession) {
      throw new Error(
        'Выход невозможен: нативный модуль сессий не собран. Переустановите приложение.',
      );
    }
    await NativeWebSession.clearCookies([...origins]);
  },

  /**
   * Дожать свежую сессию на диск. Безопасно вызывать всегда: это подстраховка
   * после входа, и отсутствие модуля здесь ничего не ломает — сессия просто
   * сохранится тогда, когда WebView соберётся сделать это сам.
   */
  flush(): void {
    NativeWebSession?.flush();
  },
};
