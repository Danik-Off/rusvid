/**
 * Управление cookie-сессиями сайтов платформ.
 *
 * Своя нативная спецификация, потому что из JS до системного хранилища
 * cookie не дотянуться: `WebView` и сетевой стек React Native делят
 * `android.webkit.CookieManager`, но наружу его не отдают. Без этого
 * приложение не может сделать двух вещей, которые пользователь считает
 * само собой разумеющимися:
 *
 *  1. **Выйти.** Кнопка «Выйти» очищала только внутреннюю отметку «вход был»,
 *     а cookie сайта оставались. Ближайшая же проверка сессии (она идёт при
 *     каждом открытии настроек) находила живой вход и возвращала «Вход
 *     выполнен» — то есть выход не работал вовсе, а пользователь считал,
 *     что вышел.
 *  2. **Пережить перезапуск.** WebView сбрасывает cookie на диск лениво.
 *     Если приложение убить из недавних вскоре после входа, свежая сессия
 *     не успевает сохраниться, и вход приходится повторять.
 *
 * Кодогенерация собирает из этого файла абстрактный класс
 * `NativeWebSessionSpec` (см. `codegenConfig` в package.json), который
 * реализует `android/app/src/main/java/com/rusvid/web/WebSessionModule.kt`.
 */

import type { TurboModule } from 'react-native';
import { TurboModuleRegistry } from 'react-native';

export interface Spec extends TurboModule {
  /**
   * Погасить cookie на перечисленных origin'ах — это и есть выход с сайта.
   *
   * Списком, а не по одному: сессия платформы живёт сразу на нескольких
   * доменах (у VK это и `vk.com`, и `vkvideo.ru`), и выход с одного из них
   * ничего не даёт — оставшийся домен тут же восстановит сессию autologin'ом.
   *
   * Точечно, а не `removeAllCookies()`: выход из одной платформы не должен
   * выкидывать пользователя из двух остальных.
   */
  clearCookies(origins: Array<string>): Promise<void>;

  /** Дожать cookie на диск. Вызывается сразу после успешного входа. */
  flush(): void;
}

/**
 * `get`, а не `getEnforcing`: если модуль не собрался, приложение должно
 * остаться рабочим. Деградация честная и видимая — см. `webSession.ts`,
 * где отсутствие модуля превращается в осмысленную ошибку у кнопки «Выйти»,
 * а не в молчаливое «как будто вышли».
 */
export default TurboModuleRegistry.get<Spec>('WebSession');
